#!/usr/bin/env python3
"""Write src/ca_roots.h: the public root CAs the firmware trusts for HTTPS.

api.openai.com and api.anthropic.com sit behind CDNs whose certificates chain
to one of a handful of public roots. Pinning that handful keeps verification on
without shipping the full Mozilla bundle. If a handshake starts failing after a
provider changes CA, add its root here and re-run:

    python3 tools/make_ca_roots.py [/etc/ssl/certs]
"""
import hashlib
import ssl
import sys
from datetime import date
from pathlib import Path

ROOTS = [
    "ISRG_Root_X1",  # Let's Encrypt
    "ISRG_Root_X2",
    "GTS_Root_R1",  # Google Trust Services (Cloudflare, Google)
    "GTS_Root_R3",
    "GTS_Root_R4",
    "GlobalSign_Root_CA_-_R3",
    "DigiCert_Global_Root_G2",
    "DigiCert_Global_Root_G3",
    "SSL.com_TLS_RSA_Root_CA_2022",
    "SSL.com_TLS_ECC_Root_CA_2022",
    "SSL.com_Root_Certification_Authority_RSA",
    "SSL.com_Root_Certification_Authority_ECC",
    "USERTrust_RSA_Certification_Authority",  # Sectigo
    "USERTrust_ECC_Certification_Authority",
    "Amazon_Root_CA_1",
]


def main() -> None:
    cert_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs")
    out = Path(__file__).resolve().parent.parent / "src" / "ca_roots.h"
    lines = [
        "// Generated by tools/make_ca_roots.py on %s. Do not edit by hand." % date.today(),
        "// Root CAs trusted for api.openai.com and api.anthropic.com.",
        "#pragma once",
        "",
    ]
    pems = []
    for name in ROOTS:
        pem = (cert_dir / f"{name}.pem").read_text().strip()
        der = ssl.PEM_cert_to_DER_cert(pem)
        lines.append(f"// {name} sha256:{hashlib.sha256(der).hexdigest()}")
        pems.append(pem)
    lines += ["", 'static const char CA_ROOTS[] PROGMEM = R"PEM(']
    lines += ["\n".join(pems), ')PEM";', ""]
    out.write_text("\n".join(lines))
    print(f"wrote {out} with {len(pems)} roots")


if __name__ == "__main__":
    main()
